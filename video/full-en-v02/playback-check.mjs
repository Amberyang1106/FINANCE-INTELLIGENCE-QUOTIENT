import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const store=path.resolve(root,'../launch-preview/node_modules/.pnpm');
const dir=(await fs.readdir(store)).find(s=>s.startsWith('puppeteer-core@'));
const {default:pup}=await import(pathToFileURL(path.join(store,dir,'node_modules/puppeteer-core/lib/puppeteer/puppeteer-core.js')));
const browser=await pup.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage();await page.setViewport({width:1440,height:1080,deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4175/video/full-en-v02/watch.html',{waitUntil:'networkidle0'});
await page.waitForFunction(()=>document.querySelector('video').readyState>=2,{timeout:30000});
const metadata=await page.evaluate(()=>{const v=document.querySelector('video');return {width:v.videoWidth,height:v.videoHeight,duration:v.duration,readyState:v.readyState,error:v.error?.message||null};});
await page.evaluate(async()=>{const v=document.querySelector('video');v.muted=true;await v.play();});
await new Promise(r=>setTimeout(r,1200));
const played=await page.evaluate(()=>{const v=document.querySelector('video');return {time:v.currentTime,paused:v.paused,decoded:v.webkitDecodedFrameCount};});
await page.evaluate(async()=>{const v=document.querySelector('video');v.pause();v.currentTime=66;await new Promise(r=>v.addEventListener('seeked',r,{once:true}));});
await page.screenshot({path:path.join(root,'renders/browser-player.png')});
const result={metadata,played,errors,pass:metadata.width===3840&&metadata.height===2160&&metadata.duration===170&&!metadata.error&&played.time>0&&played.decoded>0&&errors.length===0,note:'Headless muted playback/seek verification. This is not an audible listening review.'};
await fs.writeFile(path.join(root,'browser-playback-check.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result));await browser.close();if(!result.pass)process.exitCode=1;
