const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const assert=require('node:assert/strict');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'knowledge-model.js'),'utf8'),context);
const m=context.FPAKnowledgeModel;
let count=0;
function check(name,value){assert.ok(value,name);count++;}
const all=[m.builtin];
const broad=m.retrieve(all,'isg-service','all','pls tell me the allocation logic for ISG Service?');
check('Broad question retrieves six rule sections',broad.hits.length===6);
check('Scope first',broad.hits[0].sectionId==='allocation-scope');
check('True-up included',broad.hits.some(h=>h.sectionId==='quarter-true-up'));
check('Both built-in files used',new Set(broad.hits.map(h=>h.sourceId)).size===2);
check('History lock retained',broad.hits.some(h=>h.text.includes('months 1–2 stay locked')));
check('No fabricated embedding metadata',!JSON.stringify(broad).includes('confidence'));
const field=m.retrieve(all,'isg-service','all','What does non_alloc_flg mean?');
check('Field-specific answer ranks its definition first',field.hits[0].sectionId==='non-allocation');
check('Before/after flag definition retrieved',m.retrieve(all,'isg-service','all','checking_flg').hits[0].sectionId==='checking-flag');
check('No cross-report knowledge leak',m.retrieve(all,'row-psd','all','allocation logic').hits.length===0);
check('Unknown question has no answer source',m.retrieve(all,'isg-service','all','zebraprotocol987').hits.length===0);
check('Missing library yields no fallback',m.retrieve(all,'isg-service','missing','allocation logic').hits.length===0);
const sections=m.sectionsFromText('Expense review requires a named reviewer.\n\nRetain the supporting source reference.','Close review policy');
check('Paragraphs become separate cards',sections.length===2);
check('Source text is retained exactly',sections[0].text==='Expense review requires a named reviewer.');
check('Blank text creates no cards',m.sectionsFromText('   ','Empty').length===0);
const personal={id:'personal',name:'My Close Policy',report:'row-psd',sources:[{id:'note',name:'Close review policy',type:'note',sections:sections}]};
const own=m.retrieve(all.concat(personal),'row-psd','personal','Expense review');
check('Personal content is actually retrieved',own.hits.some(h=>h.text.includes('named reviewer')));
check('Personal content stays in its report',m.retrieve(all.concat(personal),'isg-service','personal','Expense review').hits.length===0);
check('Library selection excludes built-in',m.retrieve(all.concat(personal),'row-psd','personal','Expense review').hits.every(h=>h.baseId==='personal'));
const link={id:'link-base',name:'Links',report:'row-psd',sources:[{id:'url',name:'Expense policy',type:'link',sections:[]}]};
check('Reference-only URL is not a fabricated source',m.retrieve([link],'row-psd','all','Expense policy').hits.length===0);
check('Reference-only URL is not counted searchable',m.retrieve([link],'row-psd','all','Expense policy').sourceCount===0);
const snapshot=JSON.parse(JSON.stringify(own.hits));
personal.sources[0].sections[0].text='Edited policy';
check('Citation snapshot survives source edits',snapshot.some(h=>h.text.includes('named reviewer')));
check('Long text is bounded into cards',m.sectionsFromText('x'.repeat(3400),'Long').every(s=>s.text.length<=1600));
const precise={id:'precise',name:'Review',report:'row-psd',sources:[{id:'a',name:'Counterpart policy',type:'note',sections:[{id:'a',title:'Counterpart review policy',kind:'source',tags:[],text:'Counterpart review requires finance confirmation.'}]},{id:'b',name:'Other',type:'note',sections:[{id:'b',title:'Other record',kind:'source',tags:[],text:'This review marker is unrelated.'}]}]};
check('Weak unrelated matches are not appended to an answer',m.retrieve([precise],'row-psd','all','counterpart review policy').hits.length===1);
console.log(count+' knowledge retrieval and provenance checks passed.');
